export const toBn = (n: any, fallback = '০'): string => {
  if (n === undefined || n === null || n === '' || (typeof n === 'number' && isNaN(n))) {
    return fallback;
  }
  return String(n).replace(/\d/g, d => '০১২৩৪৫৬৭৮৯'[parseInt(d, 10)]);
};

