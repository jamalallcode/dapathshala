// --------------------------------------------------------------------------
// 3. Multi-Chapter Query & Generator Function (১ বা একাধিক অধ্যায় একত্রীকরণ)
// --------------------------------------------------------------------------
export interface MultiChapterQueryOptions {
  selectedClass: string;
  selectedSubject: string;
  selectedChapters: string[]; // একাধিক অধ্যায় একসঙ্গে
  difficulty?: DifficultyLevel;
  count: number;
  excludeIds?: string[];
}

export function getQuestionsFromNCTBBank(options: MultiChapterQueryOptions): NCTBQuestion[] {
  const {
    selectedClass,
    selectedSubject,
    selectedChapters,
    difficulty = 'all',
    count,
    excludeIds = []
  } = options;

  const excludeSet = new Set(excludeIds);

  // Filter pool matching class (or normalized), subject, and any of selected chapters
  let filtered = MASTER_NCTB_QUESTIONS.filter(q => {
    if (excludeSet.has(q.id)) return false;

    // Match subject loosely or strictly
    const matchSubject = q.subject.includes(selectedSubject) || selectedSubject.includes(q.subject);
    if (!matchSubject) return false;

    // Multi-chapter match
    if (selectedChapters.length > 0) {
      const matchChap = selectedChapters.some(chap => 
        q.chapter.includes(chap) || chap.includes(q.chapter)
      );
      if (!matchChap) return false;
    }

    // Match difficulty if specified
    if (difficulty !== 'all' && q.difficulty !== difficulty) {
      return false;
    }

    return true;
  });

  // If filtered pool is smaller than required count, allow related questions from same subject
  if (filtered.length < count) {
    const backupPool = MASTER_NCTB_QUESTIONS.filter(q => 
      !excludeSet.has(q.id) &&
      (q.subject.includes(selectedSubject) || selectedSubject.includes(q.subject)) &&
      !filtered.some(f => f.id === q.id)
    );
    filtered = [...filtered, ...backupPool];
  }

  // Shuffle candidate list
  const shuffled = [...filtered];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled.slice(0, count);
}

// --------------------------------------------------------------------------
// 4. Single Alternative Question Swapper (ম্যানুয়াল মোডে এক ক্লিকে বিকল্প প্রশ্ন আনা)
// --------------------------------------------------------------------------
export function getAlternativeNCTBQuestion(
  selectedSubject: string,
  selectedChapters: string[],
  excludeQuestionTexts: string[],
  difficulty: DifficultyLevel = 'all'
): NCTBQuestion | null {
  const excludeSet = new Set(excludeQuestionTexts.map(t => t.trim()));

  const candidates = MASTER_NCTB_QUESTIONS.filter(q => {
    if (excludeSet.has(q.question.trim())) return false;
    const matchSub = q.subject.includes(selectedSubject) || selectedSubject.includes(q.subject);
    if (!matchSub) return false;

    if (selectedChapters.length > 0) {
      const matchChap = selectedChapters.some(chap => q.chapter.includes(chap) || chap.includes(q.chapter));
      if (!matchChap) return false;
    }

    if (difficulty !== 'all' && q.difficulty !== difficulty) return false;

    return true;
  });

  if (candidates.length === 0) return null;

  const pick = candidates[Math.floor(Math.random() * candidates.length)];
  return pick;
}
